/**
 * Renders the guides: for each artboard, an orthographic drawing of the car aligned
 * exactly to the artboard's frame, to draw a design over, and the car's feature lines
 * as vector paths in the artboard's millimetres, to measure and snap to.
 *
 *   pnpm guides
 *
 * Writes designs/_guides/<view>.png, the drawing with the feature lines drawn over it,
 * and designs/_guides/<view>-lines.svg, the feature lines alone. Run it again whenever
 * the car model changes. It reads only the car model contract.
 */
import { mkdirSync, writeFileSync } from "node:fs";

import { Resvg } from "@resvg/resvg-js";
import type { Gpu } from "vgpu";
import { init, target } from "vgpu/node";

import type { SurfaceClass } from "../src/car/index.ts";
import { FRAMES, VIEWS, type View } from "../src/frames.ts";
import { createScene, type Scene } from "../src/scene.ts";
import { decodeSurface, renderAligned, surfaceCode } from "./lib/aligned.ts";
import { readCarModel } from "./lib/car.ts";
import { REPOSITORY } from "./lib/design.ts";
import { encodePng, writePng } from "./lib/png.ts";
import { loadSceneShaders } from "./lib/shaders.ts";
import {
  columnExtremes,
  labelComponents,
  simplify,
  traceContours,
  withoutSmall,
} from "./lib/trace.ts";

/** Guide pixels per artboard millimetre. */
const SCALE = 0.5;
/** The car is rendered this many times larger, then averaged down. */
const SUPERSAMPLE = 2;

type Tone = readonly [number, number, number];
const BACKGROUND: Tone = [255, 255, 255];
const OUTLINE: Tone = [84, 90, 100];
const SEAM: Tone = [112, 118, 128];
/** Flat, light tones: glass, wheels, lights and trim read against paint. */
const TONES: Record<SurfaceClass, Tone> = {
  paint: [228, 231, 236],
  glass: [164, 198, 228],
  wheel: [158, 160, 166],
  light: [250, 208, 122],
  trim: [124, 128, 136],
};

/** The feature lines are traced at one pixel per millimetre. */
const LINE_SCALE = 1;
/** How far, in millimetres, a simplified line may stray from the traced pixel edge. */
const TOLERANCE = 0.75;
/** A wheel is a wheel piece at least this large, in square millimetres (0.05 m²). */
const WHEEL_AREA = 50_000;
/** Length of each of the two lines of a wheel-centre cross, in millimetres. */
const CROSS = 160;
/**
 * Pieces of a mask smaller than this, in pixels, are dropped before it is traced: specks
 * become no outline, and stray patches no spike on a feature line.
 */
const OUTLINE_MIN_AREA = 2_000;
const EDGE_MIN_AREA = 20_000;

const gpu = await init();
try {
  const scene = await createScene(
    gpu,
    target(gpu, { size: [8, 8] }),
    await loadSceneShaders(),
    readCarModel(),
  );
  const directory = `${REPOSITORY}designs/_guides`;
  mkdirSync(directory, { recursive: true });

  for (const view of VIEWS) {
    const { width, height } = FRAMES[view];
    const lines = await featureLines(gpu, scene, view);
    const linesFile = `${directory}/${view}-lines.svg`;
    writeFileSync(
      linesFile,
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}mm" height="${height}mm">\n` +
        `  <!-- Feature lines of the car on the ${view.toUpperCase()} artboard. 1 user unit = 1 mm.\n` +
        `       Generated by \`pnpm guides\` from the car model: do not edit, run it again. -->\n` +
        `${lines}</svg>\n`,
    );

    const guide = await drawGuide(gpu, scene, view);
    const file = `${directory}/${view}.png`;
    writePng(file, guide.width, guide.height, overlay(guide, view, lines));
    console.log(file);
    console.log(linesFile);
  }
} finally {
  gpu.dispose();
}

/** The flat drawing of the car on an artboard, at the guide's size: RGBA bytes. */
async function drawGuide(gpu: Gpu, scene: Scene, view: View) {
  const { width, height, values } = await renderAligned(
    gpu,
    scene,
    FRAMES[view],
    SCALE * SUPERSAMPLE,
    { output: "surface", seamPixels: 1.5 * SUPERSAMPLE },
  );

  // One code per pixel: 0 background, 1..5 a surface class, 6 a seam.
  const codes = new Uint8Array(width * height);
  for (let i = 0; i < codes.length; i++) {
    const sample = decodeSurface(surfaceCode(values[i * 4 + 3]));
    if (!sample) continue;
    codes[i] = sample.seam ? 6 : 1 + Object.keys(TONES).indexOf(sample.surface);
  }
  const tones = [BACKGROUND, ...Object.values(TONES), SEAM];

  // Outline wherever the class changes: the silhouette and every part boundary.
  const outline = new Uint8Array(width * height);
  const reach = SUPERSAMPLE;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const code = codes[y * width + x];
      if (code === 6) continue;
      const right = x + 1 < width ? codes[y * width + x + 1] : code;
      const below = y + 1 < height ? codes[(y + 1) * width + x] : code;
      if ((right === code || right === 6) && (below === code || below === 6)) continue;
      for (let dy = -reach + 1; dy <= reach; dy++) {
        for (let dx = -reach + 1; dx <= reach; dx++) {
          const ox = x + dx;
          const oy = y + dy;
          if (ox >= 0 && ox < width && oy >= 0 && oy < height) outline[oy * width + ox] = 1;
        }
      }
    }
  }

  // Average down to the guide's size.
  const guideWidth = width / SUPERSAMPLE;
  const guideHeight = height / SUPERSAMPLE;
  const rgba = new Uint8Array(guideWidth * guideHeight * 4);
  for (let y = 0; y < guideHeight; y++) {
    for (let x = 0; x < guideWidth; x++) {
      const sum = [0, 0, 0];
      for (let sy = 0; sy < SUPERSAMPLE; sy++) {
        for (let sx = 0; sx < SUPERSAMPLE; sx++) {
          const i = (y * SUPERSAMPLE + sy) * width + x * SUPERSAMPLE + sx;
          const tone = outline[i] ? OUTLINE : tones[codes[i]];
          sum[0] += tone[0];
          sum[1] += tone[1];
          sum[2] += tone[2];
        }
      }
      const at = (y * guideWidth + x) * 4;
      const samples = SUPERSAMPLE * SUPERSAMPLE;
      rgba[at] = Math.round(sum[0] / samples);
      rgba[at + 1] = Math.round(sum[1] / samples);
      rgba[at + 2] = Math.round(sum[2] / samples);
      rgba[at + 3] = 255;
    }
  }
  return { width: guideWidth, height: guideHeight, rgba };
}

/**
 * The feature lines of the car on an artboard, as the SVG groups of the lines file, in
 * artboard millimetres.
 */
async function featureLines(gpu: Gpu, scene: Scene, view: View): Promise<string> {
  const { width, height, values } = await renderAligned(gpu, scene, FRAMES[view], LINE_SCALE, {
    output: "surface",
  });

  // Paint that takes its livery from this artboard, and the parts that take none.
  const reach = new Uint8Array(width * height);
  const glass = new Uint8Array(width * height);
  const lights = new Uint8Array(width * height);
  const wheels = new Uint8Array(width * height);
  for (let i = 0; i < reach.length; i++) {
    const sample = decodeSurface(surfaceCode(values[i * 4 + 3]));
    if (!sample || sample.seam) continue;
    if (sample.surface === "paint" && sample.artboard === view) reach[i] = 1;
    else if (sample.surface === "glass") glass[i] = 1;
    else if (sample.surface === "light") lights[i] = 1;
    else if (sample.surface === "wheel") wheels[i] = 1;
  }

  const outlines = (mask: Uint8Array) =>
    path(
      traceContours(withoutSmall(mask, width, height, OUTLINE_MIN_AREA), width, height)
        .map((contour) => simplify(toMillimetres(contour), TOLERANCE, true))
        // A speck of a pixel or two simplifies to a line with no inside.
        .filter((contour) => contour.length >= 3),
      true,
    );
  const edge = (mask: Uint8Array, which: "top" | "bottom") =>
    path(
      columnExtremes(withoutSmall(mask, width, height, EDGE_MIN_AREA), width, height, which)
        .map((line) => simplify(toMillimetres(line), TOLERANCE, false))
        .filter((line) => line.length >= 2),
      false,
    );

  const groups = [
    group(
      'id="reach" fill="none" stroke="#d6336c" stroke-width="2"',
      "Reach: the paint that takes its livery from this artboard. Where a graphic crosses this line it must meet the next artboard.",
      outlinePath(outlines(reach)),
    ),
    group(
      'id="glass" fill="none" stroke="#1c7ed6" stroke-width="1.5"',
      "Glass outlines: glass never takes livery.",
      outlinePath(outlines(glass)),
    ),
    group(
      'id="lights" fill="none" stroke="#f08c00" stroke-width="1.5"',
      "Light outlines: lights never take livery.",
      outlinePath(outlines(lights)),
    ),
    group(
      'id="wheels" fill="none" stroke="#495057" stroke-width="1.5"',
      "Wheel outlines: wheels never take livery.",
      outlinePath(outlines(wheels)),
    ),
  ];

  if (view === "left" || view === "right") {
    const feature = (id: string, title: string, d: string) =>
      d === "" ? "" : `    <path id="${id}" d="${d}"><title>${title}</title></path>\n`;
    groups.push(
      group(
        'id="feature-lines" fill="none" stroke="#2f9e44" stroke-width="2.5"',
        "Feature lines: beltline, shoulder and sill.",
        feature("beltline", "Beltline: the bottom edge of the glass.", edge(glass, "bottom")) +
          feature("shoulder", "Shoulder: the top edge of the reach.", edge(reach, "top")) +
          feature("sill", "Sill: the bottom edge of the reach.", edge(reach, "bottom")),
      ),
    );

    const { components: pieces, labels } = labelComponents(wheels, width, height);
    const centres = pieces
      .map((piece, index) => ({ ...piece, label: index + 1 }))
      .filter(({ area }) => area / (LINE_SCALE * LINE_SCALE) >= WHEEL_AREA)
      .map(({ minX, minY, maxX, maxY, label }) => {
        // A lopsided outline puts its bounding box off the hub sideways; the row through
        // the box's middle spans the wheel from edge to edge.
        const middle = (minY + maxY + 1) / 2;
        const row = Math.min(maxY, Math.floor(middle)) * width;
        let first = maxX;
        let last = minX;
        for (let x = minX; x <= maxX; x++) {
          if (labels[row + x] !== label) continue;
          first = Math.min(first, x);
          last = Math.max(last, x);
        }
        const u = (first + last + 1) / 2 / LINE_SCALE;
        const v = middle / LINE_SCALE;
        const arm = CROSS / 2;
        const cross =
          `M${mm(u - arm)} ${mm(v)} L${mm(u + arm)} ${mm(v)} ` +
          `M${mm(u)} ${mm(v - arm)} L${mm(u)} ${mm(v + arm)}`;
        return (
          `    <path d="${cross}"/>\n` +
          `    <text x="${mm(u + arm + 10)}" y="${mm(v - 16)}" stroke="none">u ${Math.round(u)} v ${Math.round(v)}</text>\n`
        );
      });
    groups.push(
      group(
        'id="wheel-centres" fill="#2f9e44" stroke="#2f9e44" stroke-width="2" font-family="sans-serif" font-size="48"',
        "Wheel centres, in artboard millimetres: v is the middle of the wheel's outline, u the middle of the row through it.",
        centres.join(""),
      ),
    );
  }
  return groups.join("");
}

/** The guide drawing with the feature lines drawn over it, at the drawing's size. */
function overlay(
  guide: { width: number; height: number; rgba: Uint8Array },
  view: View,
  lines: string,
): Uint8Array {
  const { width, height } = FRAMES[view];
  const href = `data:image/png;base64,${encodePng(guide.width, guide.height, guide.rgba).toString("base64")}`;
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${width} ${height}" width="${guide.width}" height="${guide.height}">` +
    `<image x="0" y="0" width="${width}" height="${height}" image-rendering="optimizeSpeed" xlink:href="${href}"/>` +
    `${lines}</svg>`;
  const image = new Resvg(svg, {
    fitTo: { mode: "width", value: guide.width },
    font: { loadSystemFonts: true },
  }).render();
  if (image.width !== guide.width || image.height !== guide.height) {
    throw new Error(
      `${view}: drew the lines at ${image.width}x${image.height}, expected ${guide.width}x${guide.height}`,
    );
  }
  // The drawing is opaque, so resvg's colour premultiplied by alpha is the colour itself.
  return new Uint8Array(image.pixels);
}

/** Pixel coordinates of the line render as artboard millimetres. */
function toMillimetres(points: number[][]): number[][] {
  return points.map(([x, y]) => [x / LINE_SCALE, y / LINE_SCALE]);
}

/** A coordinate in millimetres, rounded to 0.1 mm. */
function mm(value: number): string {
  const rounded = Math.round(value * 10) / 10;
  return String(rounded === 0 ? 0 : rounded);
}

/** Path data for polylines: `M … L …`, closed with `Z` if asked. */
function path(polylines: number[][][], closed: boolean): string {
  return polylines
    .map(
      (points) =>
        points.map(([x, y], i) => `${i === 0 ? "M" : "L"}${mm(x)} ${mm(y)}`).join(" ") +
        (closed ? " Z" : ""),
    )
    .join(" ");
}

/** A group with its attributes, a title, and its content. */
function group(attributes: string, title: string, content: string): string {
  return `  <g ${attributes}>\n    <title>${title}</title>\n${content}  </g>\n`;
}

/** A path holding a group's outlines, left out when there are none. */
function outlinePath(d: string): string {
  return d === "" ? "" : `    <path d="${d}"/>\n`;
}
